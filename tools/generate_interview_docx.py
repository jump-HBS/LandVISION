def set_font(run, name_cn="宋体", size=10.5, bold=False, color=None):
    run.font.name = "Calibri"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name_cn)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)


def build():
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    style.font.size = Pt(10.5)

    # 标题
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run("面试高频题与参考回答")
    set_font(run, "黑体", 20, bold=True, color=(0x1F, 0x3B, 0x5C))
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run("LandVISION 国土空间数据管理与智能分析可视化平台 · 基于真实项目经历")
    set_font(run, "宋体", 11, color=(0x66, 0x6E, 0x79))

    tip = doc.add_paragraph()
    tip.paragraph_format.left_indent = Pt(0)
    run = tip.add_run(
        "使用说明：本资料围绕简历中的项目经历（全栈 WebGIS、万级空间数据性能优化、"
        "Git 版本管理）编织面试官高频追问。回答均基于项目真实实现与实测数据，"
        "面试时可结合自己的表述习惯改写，但关键数字（12,747 宗、40 秒→0.3 秒、20 项测试、"
        "GiST 索引、v2.0→v4.0.3）建议保留，回答时先讲结论再讲过程。")
    set_font(run, "宋体", 9.5, color=(0x66, 0x6E, 0x79))

    for i, (question, focus, answer) in enumerate(QUESTIONS, 1):
        h = doc.add_heading("", level=2)
        run = h.add_run(f"问题 {i}：{question}")
        set_font(run, "黑体", 12.5, bold=True, color=(0x1F, 0x3B, 0x5C))
        h.paragraph_format.space_before = Pt(14)
        h.paragraph_format.space_after = Pt(4)

        fp = doc.add_paragraph()
        run = fp.add_run("【考察点】")
        set_font(run, "黑体", 10, bold=True, color=(0x2E, 0x86, 0xAB))
        run = fp.add_run(focus)
        set_font(run, "宋体", 10, color=(0x2E, 0x86, 0xAB))

        ap = doc.add_paragraph()
        run = ap.add_run("【参考回答】")
        set_font(run, "黑体", 10, bold=True, color=(0xB4, 0x53, 0x09))
        run = ap.add_run(answer)
        set_font(run, "宋体", 10.5)
        ap.paragraph_format.line_spacing = 1.3

    os.makedirs(OUT_DIR, exist_ok=True)
    doc.save(OUT_DOCX)
    print(f"[OK] 已生成：{OUT_DOCX}")
    print(f"[OK] 共 {len(QUESTIONS)} 道高频题")


if __name__ == "__main__":
    build()
